import { describe, expect, it } from 'vitest';

/**
 * Гостевой вход: сервис открыт всем.
 *
 * До 10 сентября 2026 корень домена отвечал служебным JSON «нужна
 * инвайт-ссылка»: сервис работал, а выглядел сломанным для каждого, кто
 * набрал адрес руками. Решение CEO — пускать всех. Токен при этом остался,
 * и не как барьер, а как то, на чём держится всё остальное: паки
 * принадлежат владельцу по токену, месячный счёт ведётся по нему же.
 *
 * Разбор куки и формат гостевого токена проверяются здесь, потому что
 * ошибка в них тихая: человек вернётся в пустой кабинет и решит, что его
 * работа пропала.
 */

/** Копия разбора из сервера: та же строка формата, что и в main.ts. */
const GUEST_TOKEN = /^g-[0-9a-f]{24,48}$/;

function cookieOf(header: string, name: string): string | null {
  for (const part of header.split(';')) {
    const [k, ...v] = part.trim().split('=');
    if (k === name) return decodeURIComponent(v.join('='));
  }
  return null;
}

describe('гостевой токен', () => {
  it('токен, выданный сервером, признаётся своим', () => {
    // Шестнадцать байт в шестнадцатеричной записи — тридцать два символа.
    expect(GUEST_TOKEN.test(`g-${'a1b2c3d4'.repeat(4)}`)).toBe(true);
  });

  it('подделки и мусор гостем не считаются', () => {
    for (const bad of ['g-', 'g-короткий', 'guest-123', `g-${'z'.repeat(32)}`, '../../etc/passwd'])
      expect(GUEST_TOKEN.test(bad), bad).toBe(false);
  });

  it('именной токен приглашения под гостевой формат не подходит', () => {
    // Иначе чужое приглашение можно было бы угадать по форме.
    expect(GUEST_TOKEN.test('localdemo1234567890')).toBe(false);
  });
});

describe('кука сессии', () => {
  it('читается среди прочих кук', () => {
    expect(cookieOf('theme=dark; sid=g-abc; other=1', 'sid')).toBe('g-abc');
  });

  it('отсутствие куки — не ошибка, а первый заход', () => {
    expect(cookieOf('theme=dark', 'sid')).toBeNull();
    expect(cookieOf('', 'sid')).toBeNull();
  });

  it('имя куки совпадает целиком, а не по началу', () => {
    // Иначе «sidebar=1» прочиталось бы как сессия.
    expect(cookieOf('sidebar=1', 'sid')).toBeNull();
  });
});
